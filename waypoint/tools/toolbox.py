"""BigQuery behind MCP Toolbox for Databases.

Toolbox (github.com/googleapis/mcp-toolbox) is a server that exposes pre-written, parameterised SQL as tools,
over MCP and a small HTTP API. Waypoint's allow-list (NAMED_QUERIES) becomes Toolbox's tools.yaml, so the
SQL lives in one place and Toolbox, not Waypoint, holds the BigQuery credentials and enforces:
- read-only access to the `waypoint` dataset only (allowedDatasets, writeMode: blocked),
- a 50 MB per-query billing cap (maximumBytesBilled),
- parameters bound as BigQuery query parameters, never string-spliced.

    python -m waypoint.tools.toolbox > infra/toolbox/tools.yaml     # regenerate (a test checks it's current)
    toolbox --config infra/toolbox/tools.yaml                        # serves :5000
    WAYPOINT_CATALOG=toolbox ...                                     # Waypoint calls it via ToolboxCatalog
"""

import json
import re
from typing import Any

import httpx

from waypoint.tools.catalog import NAMED_QUERIES

SOURCE = "waypoint-bigquery"
MAX_BYTES_BILLED = 50 * 1024 * 1024
TOOL_DESCRIPTIONS = {
    "get_course": "One UTM course by code prefix (e.g. MAT224 or MAT224H5): prerequisites, exclusions, credits.",
    "search_courses": "Courses whose title or description matches a LIKE pattern, optionally in one department.",
    "courses_unlocked_by": "Courses that list the given course code among their prerequisites.",
    "get_program": "A program by exact code or by a LIKE pattern on its name, with completion requirements.",
    "list_programs": "Every program in Waypoint's data: code, name, type, area.",
}
PARAM_DESCRIPTIONS = {
    "code": "Course or program code, upper case, e.g. MAT224 or ERMAJ2511.",
    "pattern": "Lower-case SQL LIKE pattern, e.g. %linear algebra%.",
    "department": "Department prefix like MAT, or empty for all.",
}


def query_params(sql: str) -> list[str]:
    return list(dict.fromkeys(re.findall(r"@(\w+)", sql)))


def render_tools_yaml(project: str, dataset: str) -> str:
    """tools.yaml for Toolbox, generated from NAMED_QUERIES so the allow-list can't drift between the two."""
    docs = [
        "\n".join(
            [
                "# Generated by `python -m waypoint.tools.toolbox`; do not edit by hand.",
                "kind: source",
                f"name: {SOURCE}",
                "type: bigquery",
                f"project: {project}",
                "location: US",
                "writeMode: blocked",
                "allowedDatasets:",
                f"  - {project}.{dataset}",
                f"maximumBytesBilled: {MAX_BYTES_BILLED}",
            ]
        )
    ]
    for name, sql in NAMED_QUERIES.items():
        lines = [
            "kind: tool",
            f"name: {name}",
            "type: bigquery-sql",
            f"source: {SOURCE}",
            f"description: {json.dumps(TOOL_DESCRIPTIONS[name])}",
            "statement: |",
            f"  {sql.replace('{dataset}', f'{project}.{dataset}')}",
        ]
        params = query_params(sql)
        if params:
            lines.append("parameters:")
            for param in params:
                lines += [
                    f"  - name: {param}",
                    "    type: string",
                    f"    description: {json.dumps(PARAM_DESCRIPTIONS[param])}",
                ]
        docs.append("\n".join(lines))
    docs.append("\n".join(["kind: toolset", "name: waypoint_catalog", "tools:", *[f"  - {n}" for n in NAMED_QUERIES]]))
    return "\n---\n".join(docs) + "\n"


class ToolboxCatalog:
    """Catalog backend that calls Toolbox's HTTP API (POST /api/tool/<name>/invoke) instead of BigQuery."""

    def __init__(self, url: str, client: httpx.Client | None = None) -> None:
        self.url = url.rstrip("/")
        self._client = client or httpx.Client(timeout=20)

    def run(self, name: str, params: dict[str, Any]) -> list[dict[str, Any]]:
        if name not in NAMED_QUERIES:
            raise ValueError(f"query {name!r} is not allow-listed")
        # Toolbox requires every declared parameter; the in-process backends treat missing ones as ''.
        body = {p: params.get(p, "") for p in query_params(NAMED_QUERIES[name])}
        response = self._client.post(f"{self.url}/api/tool/{name}/invoke", json=body)
        response.raise_for_status()
        # Toolbox wraps rows as a JSON string under "result"; an empty result is the string "null".
        rows = json.loads(response.json().get("result") or "null")
        return rows or []


if __name__ == "__main__":
    from waypoint.config import get_settings

    settings = get_settings()
    print(render_tools_yaml(settings.gcp_project, settings.bq_dataset), end="")
